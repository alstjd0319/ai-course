import re

def format_phone_number(phone):
    """
    전화번호를 입력받아 '010-XXXX-XXXX' 형식으로 정리합니다.
    """
    # 1. 숫자 이외의 모든 문자(하이픈, 공백, 괄호 등)를 제거합니다.
    digits = re.sub(r'\D', '', str(phone))
    
    # 2. 숫자의 길이에 따라 형식을 맞춥니다.
    length = len(digits)
    
    if length == 10:
        # 02-123-4567 또는 031-123-4567 같은 경우 (지역번호 2자리 + 국번 3자리)
        # 또는 010-123-4567 같은 경우 (휴대폰 국번 3자리)
        # 여기서는 일반적인 010-1234-5678 패턴을 위해 3-4-4 구조를 기본으로 하되 
        # 길이에 맞춰 슬라이싱합니다.
        return f"{digits[:3]}-{digits[3:6]}-{digits[6:]}"
    
    elif length == 11:
        # 010-1234-5678 형식
        return f"{digits[:3]}-{digits[3:7]}-{digits[7:]}"
    
    elif length == 8:
        # 내선번호나 아주 짧은 번호인 경우
        return f"{digits[:4]}-{digits[4:]}"
    
    else:
        # 형식이 맞지 않으면 숫자만 반환하거나 에러 메시지 반환
        return digits

# --- 테스트 코드 ---
test_numbers = [
    "01012345678",          # 숫자만 있는 경우
    "010-1234-5678",        # 이미 하이픈이 있는 경우
    "010.1234.5678",        # 점이 찍힌 경우
    "010 1234 5678",        # 공백이 있는 경우
    "(010)12345678",        # 괄호가 있는 경우
    "021234567",            # 지역번호 10자리 (02-123-4567 형태)
    "12345678"              # 8자리 번호
]

print(f"{'원본':<15} | {'정리 후':<15}")
print("-" * 35)
for num in test_numbers:
    print(f"{num:<15} | {format_phone_number(num):<15}")
